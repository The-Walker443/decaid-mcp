function createPlugin(host) {
  "use strict";
  const deps = {
    base: "http://localhost:8080",
    fetch: (url, init) => fetch(url, init),
    setTimeout: (fn, ms) => setTimeout(fn, ms),
    now: () => Date.now(),
    log: (message) => { try { host.log(`[${PLUGIN_ID}] ${message}`); } catch (e) { /* logging must never fail a call */ } },
  };
  const state = { scale: null, lastHeavy: null };
  const mcp = createMcp(deps, state);

  return {
    id: PLUGIN_ID,
    version: PLUGIN_VERSION,

    // Trivial on purpose: the load watchdog allows 1 s (spike Test 7).
    onLoad() {
      deps.log(`loaded ${PLUGIN_VERSION}`);
    },

    onUnload() {},

    onEvent() {},

    // Always answers with a string body; never throws, never returns null
    // (null would leave the client waiting 30 s).
    __httpRequestHandler(request) {
      let pending;
      try {
        pending = request && request.endpoint === "mcp"
          ? mcp.handle(request)
          : Promise.resolve(jsonResponse(404, { error: `no endpoint ${request && request.endpoint}` }));
      } catch (e) {
        pending = Promise.reject(e);
      }
      return Promise.resolve(pending).catch((e) => {
        deps.log(`request failed: ${e && e.stack ? e.stack : e}`);
        return jsonResponse(500, rpcError(null, -32603, `Internal error: ${e && e.message ? e.message : e}`));
      });
    },
  };
}

