const CURVE_CHANNELS = { p: "pressure", fi: "flow_in", fo: "flow_out", w: "weight", tb: "temp_basket" };
const CURVE_ROUNDING = { t: 2, p: 2, fi: 2, fo: 2, w: 1, tb: 1 };
const MAX_CURVE_POINTS = 400;
const CURVE_CHUNK = 150;
// Below this change across a segment the curve counts as steady.
const FLAT_THRESHOLD = { p: 0.2, fo: 0.15 };
// Maximum deviation from the straight line, as a fraction of the range.
const LINEARITY_TOLERANCE = 0.15;
const SHAPE_CHANNELS = { p: "pressure", fo: "flow_out" };

// Index of the time nearest to `target`; the first one on a tie, like
// Python's min(range(n), key=...). `times` is strictly increasing.
function nearestIndex(times, target) {
  let lo = 0;
  let hi = times.length;
  while (lo < hi) {
    const mid = (lo + hi) >> 1;
    if (times[mid] < target) lo = mid + 1; else hi = mid;
  }
  if (lo === 0) return 0;
  if (lo === times.length) return times.length - 1;
  return Math.abs(times[lo - 1] - target) <= Math.abs(times[lo] - target) ? lo - 1 : lo;
}

// Thins the series evenly across time. First, last and every keep_time are
// guaranteed, even above the budget.
function selectCurvePoints(rows, maxPoints, keepTimes) {
  const ordered = sortedByElapsed(rows);
  if (maxPoints === 0) return { ordered, chosen: ordered.map((_, i) => i) };
  const times = ordered.map((r) => r.elapsed);
  const budget = Math.max(2, Math.min(Math.trunc(maxPoints), MAX_CURVE_POINTS));
  const mandatory = new Set([0, ordered.length - 1]);
  for (const wanted of keepTimes || []) if (wanted !== null && wanted !== undefined) mandatory.add(nearestIndex(times, wanted));
  const effective = Math.max(budget, mandatory.size);
  let chosen;
  if (ordered.length <= effective) {
    chosen = ordered.map((_, i) => i);
  } else {
    const span = times[times.length - 1] - times[0];
    const slots = Math.max(0, effective - mandatory.size);
    const picked = new Set(mandatory);
    if (slots && span > 0) {
      for (let step = 0; step < slots; step++) {
        picked.add(nearestIndex(times, times[0] + (span * step) / Math.max(1, slots - 1)));
      }
    }
    chosen = [...picked].sort((a, b) => a - b).slice(0, effective);
  }
  return { ordered, chosen };
}

// Parallel arrays t, p, fi, fo, w, tb; a channel without any reading is left
// out. Built in chunks (rounding every value costs on the tablet).
function curveBuilder(ordered, chosen) {
  const arrays = { t: [] };
  for (const key in CURVE_CHANNELS) arrays[key] = [];
  let i = 0;
  return {
    next(count) {
      const stop = Math.min(chosen.length, i + count);
      for (; i < stop; i++) {
        const row = ordered[chosen[i]];
        arrays.t.push(pyRound(row.elapsed, CURVE_ROUNDING.t));
        for (const key in CURVE_CHANNELS) {
          const v = row[CURVE_CHANNELS[key]];
          arrays[key].push(v === null ? null : pyRound(v, CURVE_ROUNDING[key]));
        }
      }
      return i >= chosen.length;
    },
    result() {
      const curve = { t: arrays.t };
      for (const key in CURVE_CHANNELS) if (arrays[key].some((v) => v !== null)) curve[key] = arrays[key];
      return curve;
    },
  };
}

function curveArrays(ordered, chosen) {
  const b = curveBuilder(ordered, chosen);
  b.next(Infinity);
  return b.result();
}

function downsampleCurve(rows, maxPoints, keepTimes) {
  if (!rows.length) return { t: [] };
  const { ordered, chosen } = selectCurvePoints(rows, maxPoints, keepTimes);
  return curveArrays(ordered, chosen);
}

function fullCurve(rows) {
  const ordered = sortedByElapsed(rows);
  return curveArrays(ordered, ordered.map((_, i) => i));
}

function isLinear(pairs, flat) {
  if (pairs.length < 3) return true;
  let lo = Infinity;
  let hi = -Infinity;
  for (const [, v] of pairs) { if (v < lo) lo = v; if (v > hi) hi = v; }
  const span = hi - lo;
  if (span < flat) return true;
  const [t0, v0] = pairs[0];
  const [t1, v1] = pairs[pairs.length - 1];
  if (t1 === t0) return true;
  const k = (v1 - v0) / (t1 - t0);
  let deviation = 0;
  for (const [t, v] of pairs) deviation = Math.max(deviation, Math.abs(v - (v0 + k * (t - t0))));
  return deviation / span <= LINEARITY_TOLERANCE;
}

function describe(times, values, ch) {
  const pairs = [];
  for (let i = 0; i < times.length; i++) if (values[i] !== null) pairs.push([times[i], values[i]]);
  if (pairs.length < 2) return null;
  const first = pairs[0][1];
  const last = pairs[pairs.length - 1][1];
  const delta = last - first;
  const flat = FLAT_THRESHOLD[ch];
  const digits = ch === "p" ? 1 : 2;
  return {
    from: pyRound(first, digits),
    to: pyRound(last, digits),
    dir: Math.abs(delta) < flat ? "steady" : delta > 0 ? "rising" : "falling",
    linear: isLinear(pairs, flat),
  };
}

// The curve described per machine phase instead of as raw points.
function curveShape(rows, metrics) {
  const ordered = sortedByElapsed(rows);
  if (!ordered.length) return { segments: [], markers: {}, source: "none" };
  const times = ordered.map((r) => r.elapsed);
  metrics = metrics || {};
  let boundaries = phaseBoundaries(ordered);
  let source;
  if (boundaries.length) source = "machine";
  else if (metrics.pi_end !== null && metrics.pi_end !== undefined) { boundaries = [Number(metrics.pi_end)]; source = "markers"; }
  else { boundaries = []; source = "none"; }
  const t0 = times[0];
  const tn = times[times.length - 1];
  const edges = [t0, ...boundaries.filter((b) => t0 < b && b < tn), tn];
  const segments = [];
  for (let s = 0; s + 1 < edges.length; s++) {
    const start = edges[s];
    const end = edges[s + 1];
    const w = [];
    for (let i = 0; i < times.length; i++) if (times[i] >= start && times[i] <= end) w.push(i);
    if (w.length < 2) continue;
    const segment = { from: rTime(start), to: rTime(end) };
    for (const key in SHAPE_CHANNELS) {
      const column = SHAPE_CHANNELS[key];
      const d = describe(w.map((i) => times[i]), w.map((i) => (ordered[i][column] === null ? null : Number(ordered[i][column]))), key);
      if (d !== null) segment[key] = d;
    }
    segments.push(segment);
  }
  const markers = {};
  for (const name of ["t_first_drops", "pi_end", "t_peak"]) {
    if (metrics[name] !== null && metrics[name] !== undefined) markers[name] = metrics[name];
  }
  return { segments, markers, source };
}

