// Tool failures the caller should read: returned as isError results.
function ToolError(message) {
  const e = new Error(message);
  e.isToolError = true;
  return e;
}

const SLICE_TARGET_MS = 5;
const SLICE_CEILING_MS = 10;
const TOOL_DEADLINE_MS = 25000;

// One per tool call. pause() is a macrotask yield: setTimeout hands control
// back to Decaid's event loop; a resolved promise would not (the host drains
// all pending jobs in one go). Every slice between two pauses is timed.
function createSlicer(deps, label) {
  const started = deps.now();
  let sliceStart = started;
  let maxSlice = 0;
  let maxStage = null;
  let stageName = "start";
  let slices = 0;
  const over = [];
  const stages = {};
  function close() {
    const d = deps.now() - sliceStart;
    slices++;
    const key = stageName.replace(/\/[0-9a-f-]{36}$/, "/<id>");
    if (!(key in stages) || d > stages[key]) stages[key] = d;
    if (d > maxSlice) { maxSlice = d; maxStage = stageName; }
    if (d > SLICE_CEILING_MS) over.push(`${stageName} ${d} ms`);
  }
  return {
    stage(name) { stageName = name; },
    // Around an await that is not ours (a fetch): the wait does not block
    // Decaid, so it must not count as a slice.
    suspend() { close(); },
    resume() { sliceStart = deps.now(); },
    async pause() {
      close();
      if (deps.now() - started > TOOL_DEADLINE_MS) {
        const e = new Error("deadline");
        e.isDeadline = true;
        throw e;
      }
      await new Promise((resolve) => deps.setTimeout(resolve, 0));
      sliceStart = deps.now();
    },
    // Runs one synchronous stage, then pauses.
    async run(name, fn) {
      stageName = name;
      const value = fn();
      await this.pause();
      return value;
    },
    finish() {
      close();
      return { label, total_ms: deps.now() - started, slices, max_slice_ms: maxSlice, max_slice_stage: maxStage, stage_max_ms: stages, over_ceiling: over };
    },
  };
}

