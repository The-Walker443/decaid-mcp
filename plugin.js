// ============================================================ 1 rounding

// Python's round(x, n): the exact binary value rounded to n decimals, ties to
// even. Math.round would round ties up and differ from the reference.
function pyRound(x, n) {
  if (x === null || x === undefined) return null;
  if (!isFinite(x)) return x;
  n = n || 0;
  // Fast path, exact whenever the value is not within a hair of a tie: the
  // scaled value is then clearly on one side, and k / 10^n is the double
  // nearest to the decimal k*10^-n, which is what Python returns.
  const p = 10 ** n;
  const scaled = Math.abs(x) * p;
  if (n <= 15 && scaled < 1e15) {
    const floor = Math.floor(scaled);
    const frac = scaled - floor;
    if (Math.abs(frac - 0.5) > 1e-6) {
      const k = frac > 0.5 ? floor + 1 : floor;
      const value = k / p;
      return x < 0 || Object.is(x, -0) ? -value : value;
    }
  }
  const negative = x < 0 || Object.is(x, -0);
  const exact = Math.abs(x).toFixed(100);
  const dot = exact.indexOf(".");
  const intPart = exact.slice(0, dot);
  const frac = exact.slice(dot + 1);
  let digits = (intPart + frac.slice(0, n)).split("").map(Number);
  const rest = frac.slice(n);
  let up = false;
  if (rest[0] > "5") up = true;
  else if (rest[0] === "5") {
    up = /[1-9]/.test(rest.slice(1)) || digits[digits.length - 1] % 2 === 1;
  }
  if (up) {
    let i = digits.length - 1;
    while (i >= 0 && digits[i] === 9) { digits[i] = 0; i--; }
    if (i < 0) digits.unshift(1); else digits[i]++;
  }
  const s = digits.join("");
  const whole = s.slice(0, s.length - n) || "0";
  const text = n > 0 ? `${whole}.${s.slice(s.length - n)}` : whole;
  const value = Number(text);
  return negative ? -value : value;
}

// Python's f"{x:.nf}".
function pyFixed(x, n) {
  const text = Math.abs(pyRound(x, n)).toFixed(n);
  return x < 0 || Object.is(x, -0) ? `-${text}` : text;
}

const rTime = (v) => pyRound(v, 1);
const rPressure = (v) => pyRound(v, 1);
const rFlow = (v) => pyRound(v, 2);

