function jsonResponse(status, body, headers) {
  return { status, headers: Object.assign({ "Content-Type": "application/json" }, headers || {}), body: JSON.stringify(body) };
}

function rpcError(id, code, message) {
  return { jsonrpc: "2.0", id: id === undefined ? null : id, error: { code, message } };
}

function createMcp(deps, state) {
  const tools = createTools(deps, state);
  const listed = TOOLS.map((t) => ({ name: t.name, description: t.description, inputSchema: t.inputSchema, annotations: TOOL_ANNOTATIONS[t.kind] }));

  async function handle(request) {
    const method = String(request.method || "").toUpperCase();
    if (method !== "POST") return { status: 405, headers: { Allow: "POST" }, body: "" };
    const msg = request.body;
    if (msg && typeof msg === "object" && !Array.isArray(msg) && msg.jsonrpc === "2.0" && msg.method === undefined && ("result" in msg || "error" in msg)) {
      // A client's response to a server request; this server sends none.
      return { status: 202, headers: {}, body: "" };
    }
    if (!msg || typeof msg !== "object" || Array.isArray(msg) || msg.jsonrpc !== "2.0" || typeof msg.method !== "string") {
      return jsonResponse(400, rpcError(msg && !Array.isArray(msg) ? msg.id : null, -32600, "Invalid Request: one JSON-RPC 2.0 object is expected (no batches)"));
    }
    if (msg.id === undefined || msg.id === null) {
      // Notifications need no answer.
      return { status: 202, headers: {}, body: "" };
    }
    const id = msg.id;
    if (msg.method === "initialize") {
      const asked = msg.params && msg.params.protocolVersion;
      return jsonResponse(200, {
        jsonrpc: "2.0",
        id,
        result: {
          protocolVersion: PROTOCOL_VERSIONS.includes(asked) ? asked : PROTOCOL_VERSIONS[0],
          capabilities: { tools: { listChanged: false } },
          serverInfo: { name: "decaid-mcp", title: "Decaid MCP", version: PLUGIN_VERSION },
          instructions: INSTRUCTIONS,
        },
      });
    }
    if (msg.method === "ping") return jsonResponse(200, { jsonrpc: "2.0", id, result: {} });
    if (msg.method === "tools/list") return jsonResponse(200, { jsonrpc: "2.0", id, result: { tools: listed } });
    if (msg.method === "tools/call") {
      const params = msg.params || {};
      const outcome = await tools.call(params.name, params.arguments);
      if (outcome === null) return jsonResponse(200, rpcError(id, -32602, `Unknown tool: ${params.name}`));
      const result = outcome.ok
        ? { content: [{ type: "text", text: JSON.stringify(outcome.result) }], structuredContent: outcome.result, isError: false }
        : { content: [{ type: "text", text: outcome.message }], isError: true };
      return jsonResponse(200, { jsonrpc: "2.0", id, result });
    }
    return jsonResponse(200, rpcError(id, -32601, `Method not found: ${msg.method}`));
  }

  return { handle, tools };
}

