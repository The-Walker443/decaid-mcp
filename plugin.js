const BUSY_STATES = new Set([
  "espresso", "steam", "hotWater", "flush", "steamRinse", "skipStep",
  "cleaning", "descaling", "calibration", "airPurge", "selfTest", "fwUpgrade", "busy",
]);
const SCALE_PROBE_ID = "decaid-mcp-scale-probe";

function createDecaid(deps, state) {
  async function request(slicer, method, path, body) {
    const init = { method, headers: {} };
    if (body !== undefined) {
      init.headers["Content-Type"] = "application/json";
      init.body = JSON.stringify(body);
    }
    let res;
    let text;
    if (slicer) slicer.suspend();
    try {
      res = await deps.fetch(deps.base + path, init);
      text = await res.text();
    } catch (e) {
      throw ToolError(`Decaid did not answer (${method} ${path}): ${e && e.message ? e.message : e}`);
    } finally {
      if (slicer) slicer.resume();
    }
    if (slicer) slicer.stage(`parse ${method} ${path.split("?")[0]}`);
    let json = null;
    if (text) { try { json = JSON.parse(text); } catch (e) { json = null; } }
    if (slicer) await slicer.pause();
    return { status: res.status, body: json, text };
  }

  function errorText(res) {
    return (res.body && (res.body.error || res.body.message)) || res.text || `HTTP ${res.status}`;
  }

  async function ok(slicer, method, path, body, what) {
    const res = await request(slicer, method, path, body);
    if (res.status === 404) throw ToolError(`${what || path}: not found`);
    if (res.status < 200 || res.status >= 300) throw ToolError(`Decaid refused ${method} ${path.split("?")[0]} (${res.status}): ${errorText(res)}`);
    return res.body;
  }

  // Refuses heavy and write tools while the machine is working (§6.2).
  async function guard(slicer) {
    const res = await request(slicer, "GET", "/api/v1/machine/state");
    const s = res.status === 200 && res.body && res.body.state ? res.body.state.state : null;
    if (s && BUSY_STATES.has(s)) {
      throw ToolError(`The machine is busy (${s}). Ask again after the shot - nothing was computed or written.`);
    }
    return res.body && res.body.state ? res.body.state : null;
  }

  // T46: with 0-10 ratings Decaid checks the range before looking the shot
  // up (400); before that the lookup answers 404. Asked once per load.
  async function scale(slicer) {
    if (state.scale && state.scale !== "unknown") return state.scale;
    const res = await request(slicer, "PUT", `/api/v1/shots/${SCALE_PROBE_ID}`, { annotations: { enjoyment: 11 } });
    if (res.status === 404) state.scale = "0-100";
    else if (res.status === 400 && /enjoyment/i.test(res.text || "")) state.scale = "0-10";
    else state.scale = "unknown";
    return state.scale;
  }

  return { request, ok, guard, scale };
}

