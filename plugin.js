function parseNumber(value, expected) {
  if (typeof value === "boolean" || !(typeof value === "number" || typeof value === "string")) throw new Error(`${expected} is expected`);
  const n = Number(String(value).replace(",", "."));
  if (String(value).trim() === "" || !isFinite(n)) throw new Error(`${JSON.stringify(value)} is not a number`);
  return n;
}

function checkEnjoyment(value, scale) {
  const ten = scale === "0-10";
  const expected = ten ? "a number from 0 to 10, one decimal at most" : "a whole number from 0 to 100";
  const n = parseNumber(value, expected);
  const topValue = ten ? ENJOYMENT_MAX_10 : 100;
  if (n < 0 || n > topValue) throw new Error(`${value} is outside the range 0 to ${topValue} (tablet scale ${scale})`);
  if (ten) {
    if (pyRound(n, 1) !== n) throw new Error(`${JSON.stringify(value)} has more than one decimal`);
    return n;
  }
  if (n !== Math.trunc(n)) throw new Error(`${JSON.stringify(value)} is not a whole number`);
  if (n > 0 && n <= ENJOYMENT_MAX_10) {
    throw new Error(`${n} cannot be told from a 0-10 rating once Decaid moves to 0-10, and would then read ten times higher - use 0 or a value over 10`);
  }
  return n;
}

// Decaid and DYE2 store day-level dates as midnight UTC.
function checkDate(name, value, todayIso) {
  if (typeof value !== "string") throw new Error("a date as text in the format YYYY-MM-DD is expected");
  const text = value.trim();
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(text);
  const ms = m ? Date.UTC(+m[1], +m[2] - 1, +m[3]) : NaN;
  if (!m || isNaN(ms) || new Date(ms).getUTCDate() !== +m[3]) {
    throw new Error(`${JSON.stringify(text)} is not an ISO date (YYYY-MM-DD). The DE1 app writes DD.MM.YYYY; ISO is expected here.`);
  }
  const today = Date.UTC(+todayIso.slice(0, 4), +todayIso.slice(5, 7) - 1, +todayIso.slice(8, 10));
  if (ms > today && !FUTURE_DATES.has(name)) throw new Error(`${text.slice(0, 10)} lies in the future (today is ${todayIso})`);
  if (ms > today + MAX_AHEAD_DAYS * DAY_MS) throw new Error(`${text.slice(0, 10)} lies more than ${MAX_AHEAD_DAYS / 365} years ahead - that is a typo rather than a date.`);
  if (name === "roastDate" && (today - ms) / DAY_MS > MAX_ROAST_AGE_DAYS) throw new Error(`${text.slice(0, 10)} lies more than ${MAX_ROAST_AGE_DAYS / 365} years back - that is a typo rather than a roast.`);
  return new Date(ms).toISOString();
}

function coerce(ruleset, name, value, opts) {
  if (value === null) {
    if (ruleset === "workflow" && name === "targetYield") throw new Error("cannot be cleared - Decaid needs a target weight here");
    return null;
  }
  const kind = RULES[ruleset].kinds[name] || "text";
  if (kind === "enjoyment") return checkEnjoyment(value, opts.scale);
  if (kind === "weight") {
    const [lo, hi] = WEIGHT_RANGES[name];
    const n = parseNumber(value, `a number from ${lo} to ${hi} g`);
    if (n < lo || n > hi) throw new Error(`${n} g is outside the range ${lo} to ${hi} g`);
    return pyRound(n, 2);
  }
  if (kind === "date") return checkDate(name, value, opts.todayIso);
  if (kind === "bool") {
    if (typeof value === "boolean") return value;
    if (typeof value === "string" && ["true", "false"].includes(value.trim().toLowerCase())) return value.trim().toLowerCase() === "true";
    throw new Error("true or false is expected");
  }
  if (kind === "id") {
    if (typeof value !== "string" || !UUID_RE.test(value.trim())) throw new Error("an identifier is expected, as list_beans returns them");
    return value.trim();
  }
  if (kind === "string_list") {
    const list = typeof value === "string" ? value.split(",") : value;
    if (!Array.isArray(list) || list.some((v) => typeof v !== "string")) throw new Error("a list of names is expected");
    const out = list.map((v) => v.trim()).filter(Boolean);
    if (out.some((v) => v.length > 100)) throw new Error("names of at most 100 characters are expected");
    return out;
  }
  if (kind === "int_pair") {
    const pair = Array.isArray(value) ? value : typeof value === "number" ? [value, value] : null;
    if (!pair || pair.length !== 2) throw new Error("0 to 4000 metres is expected, as [min, max]");
    const [lo, hi] = pair.map((v) => parseNumber(v, "a number of metres"));
    if (lo !== Math.trunc(lo) || hi !== Math.trunc(hi) || lo < 0 || hi > 4000 || lo > hi) throw new Error("0 to 4000 metres is expected, with the lower value first");
    return [lo, hi];
  }
  if (kind === "score") return boundedNumber(value, 0, 100, "a cupping score 0-100");
  if (kind === "price") return boundedNumber(value, 0, 10000, "a price in the currency set");
  if (kind === "bag_weight") return boundedNumber(value, 0, 50000, "a weight in g");
  if (kind === "currency") {
    if (typeof value !== "string" || !/^[A-Za-z]{3}$/.test(value.trim())) throw new Error('a three-letter currency code ("EUR") is expected');
    return value.trim().toUpperCase();
  }
  if (typeof value !== "string") throw new Error("text is expected");
  if (value.length > MAX_NOTE_CHARS) throw new Error(`${value.length} characters, at most ${MAX_NOTE_CHARS} allowed`);
  return value;
}

function boundedNumber(value, lo, hi, what) {
  const n = parseNumber(value, what);
  if (n < lo || n > hi) throw new Error(`${n} is outside ${lo} to ${hi} (${what})`);
  return n;
}

// Returns the payload or throws a ToolError listing every problem.
function validateFields(ruleset, fields, opts) {
  if (!fields || typeof fields !== "object" || Array.isArray(fields) || !Object.keys(fields).length) {
    throw new ToolError(`fields is empty - at least one field is expected. Allowed on the ${ruleset}: ${rulesHelp(ruleset)}`);
  }
  const rules = RULES[ruleset];
  const problems = [];
  const payload = {};
  for (const name of Object.keys(fields)) {
    if (name in rules.blocked) { problems.push(`${name}: not writable - ${rules.blocked[name]}`); continue; }
    if (!(name in rules.allowed)) { problems.push(`${name}: unknown field on the ${ruleset}. Allowed are ${rulesHelp(ruleset)}`); continue; }
    try { payload[name] = coerce(ruleset, name, fields[name], opts || {}); }
    catch (e) { problems.push(`${name}: ${e.message}`); }
  }
  if (problems.length) throw new ToolError(problems.join("; "));
  return payload;
}

function sameValue(a, b) {
  if (a === undefined) a = null;
  if (b === undefined) b = null;
  if (typeof a === "string" && typeof b === "string" && /^\d{4}-\d{2}-\d{2}T/.test(a) && /^\d{4}-\d{2}-\d{2}T/.test(b)) {
    return instantMs(a) === instantMs(b);
  }
  if (typeof a === "number" || typeof b === "number") return a !== null && b !== null && Number(a) === Number(b);
  return canonical(a) === canonical(b);
}

// changed / unchanged / not_taken for the fields sent.
function writeOutcome(sent, before, after) {
  const changed = [];
  const unchanged = [];
  const notTaken = [];
  const beforeOut = {};
  const afterOut = {};
  for (const k of Object.keys(sent)) {
    beforeOut[k] = before ? (before[k] === undefined ? null : before[k]) : null;
    afterOut[k] = after[k] === undefined ? null : after[k];
    if (!sameValue(after[k], sent[k])) notTaken.push(k);
    else if (before && sameValue(before[k], sent[k])) unchanged.push(k);
    else changed.push(k);
  }
  return { changed, unchanged, not_taken: notTaken, before: before ? beforeOut : null, after: afterOut };
}

